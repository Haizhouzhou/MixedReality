"""Reconstruct an oriented RGB point crop with official NVIDIA NKSR on CUDA.

Example, run separately for each prepared space in the CUDA environment::

    python tools/nksr_reconstruct.py --input inputs/HG_E7_Hall.ply \
        --output meshes/HG_E7_Hall/mesh.ply --provenance inputs/provenance.json

Input and output are aligned LaMAR world coordinates, in metres, Z up. Do not
apply the original scan alignment a second time when importing this mesh.
Colours are nearest measured RGB samples, not colours generated by the model.
Only NumPy is imported until reconstruction starts; --validate-only works
without PyTorch/CUDA. The GPU environment additionally needs nksr and pykdtree.

API reference: https://github.com/nv-tlabs/NKSR/blob/public/NKSR-USAGE.md
This follows the supplied notebook's explicit GPU chunks / CPU fusion scheme.
All fields remain in CPU RAM during meshing, so very large scenes can still
require substantial host memory. max-points limits evaluation batches, not
the total mesh. No source files are changed and existing outputs are refused.
"""
from __future__ import annotations

import argparse
from datetime import datetime, timezone
import gc
import hashlib
import json
import math
import os
from pathlib import Path
import sys
import tempfile
import time

import numpy as np


FRAME = "LaMAR world; right-handed; Z up; metres; source alignment already applied"
PLY_TYPES = {"float": "<f4", "float32": "<f4", "double": "<f8", "float64": "<f8",
             "uchar": "u1", "uint8": "u1", "int": "<i4", "uint": "<u4"}
MESH_DTYPE = np.dtype([(n, "<f8") for n in ("x", "y", "z")]
                      + [(n, "u1") for n in ("red", "green", "blue")])
FACE_DTYPE = np.dtype([("count", "u1"), ("indices", "<u4", (3,))])
BLOCK_POINTS = 250_000


def sha256(path):
    digest = hashlib.sha256()
    with Path(path).open("rb") as stream:
        for block in iter(lambda: stream.read(8 * 1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def read_cloud(path):
    """Memory-map a strict vertex-only binary PLY, rejecting truncated records."""
    path = Path(path)
    fields, count, element = [], None, None
    with path.open("rb") as stream:
        if stream.readline() != b"ply\n" or stream.readline() != b"format binary_little_endian 1.0\n":
            raise ValueError("Expected binary_little_endian 1.0 PLY")
        while True:
            raw = stream.readline(4097)
            if not raw or len(raw) > 4096 or stream.tell() > 65536:
                raise ValueError("Missing or oversized PLY header")
            words = raw.decode("ascii").split()
            if not words or words[0] in ("comment", "obj_info"):
                continue
            if words[0] == "end_header":
                offset = stream.tell()
                break
            if words[0] == "element" and len(words) == 3:
                element = words[1]
                number = int(words[2])
                if number < 0:
                    raise ValueError("Negative PLY element count")
                if element == "vertex" and count is None:
                    count = number
                elif element != "vertex" and number == 0:
                    pass
                else:
                    raise ValueError("Expected a vertex-only PLY with one vertex element")
            elif words[0] == "property":
                if element == "vertex":
                    if len(words) != 3 or words[1] not in PLY_TYPES:
                        raise ValueError("Unsupported vertex property")
                    fields.append((words[2], PLY_TYPES[words[1]]))
                elif element is None:
                    raise ValueError("PLY property before element")
            else:
                raise ValueError(f"Unexpected PLY header line: {raw!r}")
    if not count:
        raise ValueError("Input point cloud is empty")
    dtype = np.dtype(fields)
    for name in ("x", "y", "z", "nx", "ny", "nz"):
        if name not in dtype.names or dtype[name].kind != "f":
            raise ValueError(f"Required floating-point property missing: {name}")
    for name in ("red", "green", "blue"):
        if name not in dtype.names or dtype[name] != np.dtype("u1"):
            raise ValueError(f"Required uint8 colour property missing: {name}")
    if path.stat().st_size != offset + count * dtype.itemsize:
        raise ValueError("PLY length does not match its declared vertices")
    return np.memmap(path, dtype=dtype, mode="r", offset=offset, shape=(count,))


def columns(records, names, dtype):
    return np.column_stack([records[n] for n in names]).astype(dtype, copy=False)


def inspect_cloud(data):
    """Validate every source record, using bounded temporary arrays."""
    lo, hi = np.full(3, np.inf), np.full(3, -np.inf)
    rgb_lo, rgb_hi = np.full(3, 255), np.zeros(3, dtype=int)
    normal_min, normal_max = math.inf, 0.
    for start in range(0, len(data), BLOCK_POINTS):
        block = data[start:start + BLOCK_POINTS]
        xyz = columns(block, ("x", "y", "z"), np.float64)
        normals = columns(block, ("nx", "ny", "nz"), np.float64)
        lengths = np.linalg.norm(normals, axis=1)
        if not np.isfinite(xyz).all() or not np.isfinite(lengths).all() or np.any(lengths <= 1e-6):
            raise ValueError(f"Nonfinite positions or invalid normals in source records starting at {start}")
        lo, hi = np.minimum(lo, xyz.min(0)), np.maximum(hi, xyz.max(0))
        colours = columns(block, ("red", "green", "blue"), np.uint8)
        rgb_lo, rgb_hi = np.minimum(rgb_lo, colours.min(0)), np.maximum(rgb_hi, colours.max(0))
        normal_min = min(normal_min, float(lengths.min()))
        normal_max = max(normal_max, float(lengths.max()))
    return {"points": len(data), "bounds": {"min": lo.tolist(), "max": hi.tolist()},
            "rgb_min": rgb_lo.tolist(), "rgb_max": rgb_hi.tolist(),
            "normal_length_min": normal_min, "normal_length_max": normal_max}


def stratified_indices(count, limit, seed):
    """At most limit records, covering the entire source with seeded strata."""
    if limit == 0 or count <= limit:
        return np.arange(count, dtype=np.int64)
    # Integral edges prevent duplicates; generate in blocks to limit workspace.
    result = np.empty(limit, dtype=np.int64)
    rng = np.random.default_rng(seed)
    for start in range(0, limit, BLOCK_POINTS):
        end = min(limit, start + BLOCK_POINTS)
        bins = np.arange(start, end, dtype=np.int64)
        # Real sources are many orders below float64's exact integer limit.
        lo = np.floor(bins.astype(np.float64) * count / limit).astype(np.int64)
        hi = np.floor((bins + 1).astype(np.float64) * count / limit).astype(np.int64)
        result[start:end] = lo + np.floor(rng.random(len(bins)) * (hi - lo)).astype(np.int64)
    return result


def voxel_representatives(xyz, voxel_size):
    """Return the first retained record in each world-aligned sampling voxel."""
    if voxel_size == 0:
        return np.arange(len(xyz), dtype=np.int64)
    origin = xyz.min(0).astype(np.float64)
    dims = [int(math.floor((float(xyz[:, i].max()) - origin[i]) / voxel_size)) + 1 for i in range(3)]
    if math.prod(dims) >= np.iinfo(np.int64).max:
        raise ValueError("Sampling grid exceeds int64 range; increase --point-voxel")
    keys = np.zeros(len(xyz), dtype=np.int64)
    for axis in range(3):
        quantized = np.floor((xyz[:, axis].astype(np.float64) - origin[axis]) / voxel_size).astype(np.int64)
        keys *= dims[axis]
        keys += quantized
    _, indices = np.unique(keys, return_index=True)
    indices.sort()
    return indices


def load_samples(data, stats, max_points, point_voxel, seed):
    indices = stratified_indices(len(data), max_points, seed)
    after_cap = len(indices)
    # Read positions in float64 to subtract the world origin before float32.
    xyz = np.empty((len(indices), 3), dtype=np.float64)
    for start in range(0, len(indices), BLOCK_POINTS):
        end = start + BLOCK_POINTS
        xyz[start:end] = columns(data[indices[start:end]], ("x", "y", "z"), np.float64)
    selected = voxel_representatives(xyz, point_voxel)
    indices, xyz = indices[selected], xyz[selected]
    centre = (np.asarray(stats["bounds"]["min"]) + np.asarray(stats["bounds"]["max"])) / 2
    xyz -= centre
    normals = np.empty((len(indices), 3), dtype=np.float32)
    colours = np.empty((len(indices), 3), dtype=np.uint8)
    for start in range(0, len(indices), BLOCK_POINTS):
        end = start + BLOCK_POINTS
        block = data[indices[start:end]]
        normal = columns(block, ("nx", "ny", "nz"), np.float64)
        normal /= np.linalg.norm(normal, axis=1)[:, None]
        normals[start:end] = normal
        colours[start:end] = columns(block, ("red", "green", "blue"), np.uint8)
    sampling = {"policy": "seeded stratified input-record cap, then first record per spatial voxel",
                "seed": seed, "max_input_points": max_points, "point_voxel_metres": point_voxel,
                "points_after_cap": after_cap, "points_after_voxel": len(indices),
                "retained_source_indices_sha256": hashlib.sha256(indices.astype("<i8", copy=False).tobytes()).hexdigest()}
    return xyz.astype(np.float32), normals, colours, centre, sampling


def preparation_record(path, input_path, input_info):
    if path is None:
        return None
    record = json.loads(Path(path).read_text())
    matches = [s for s in record["spaces"] if Path(s["ply"]).name == Path(input_path).name]
    if len(matches) != 1:
        raise ValueError("Preparation provenance must contain exactly one matching PLY filename")
    space = matches[0]
    if space["sha256"] != input_info["sha256"] or space["points"] != input_info["points"]:
        raise ValueError("Input does not match preparation provenance hash and point count")
    return {"path": str(Path(path).resolve()), "sha256": sha256(path),
            "space": space, "source": record["sources"][space["source"]]}


def mesh_statistics(vertices, faces, colours):
    if vertices.ndim != 2 or vertices.shape[1] != 3 or len(vertices) == 0:
        raise ValueError("NKSR produced no vertices or an invalid vertex array")
    if faces.ndim != 2 or faces.shape[1] != 3 or len(faces) == 0 or faces.dtype.kind not in "iu":
        raise ValueError("NKSR produced no triangles or invalid face indices")
    if colours.shape != vertices.shape or colours.dtype != np.uint8:
        raise ValueError("Every output vertex must have uint8 RGB")
    if len(vertices) > np.iinfo(np.uint32).max:
        raise ValueError("Too many vertices for the pipeline's uint32 face layout")
    lo, hi, degenerate = np.full(3, np.inf), np.full(3, -np.inf), 0
    for start in range(0, len(vertices), BLOCK_POINTS):
        block = vertices[start:start + BLOCK_POINTS]
        if not np.isfinite(block).all():
            raise ValueError("NKSR produced nonfinite vertices")
        lo, hi = np.minimum(lo, block.min(0)), np.maximum(hi, block.max(0))
    for start in range(0, len(faces), BLOCK_POINTS):
        block = faces[start:start + BLOCK_POINTS]
        if block.min() < 0 or block.max() >= len(vertices):
            raise ValueError("NKSR face references a missing vertex")
        triangle = vertices[block]
        area = np.linalg.norm(np.cross(triangle[:, 1] - triangle[:, 0], triangle[:, 2] - triangle[:, 0]), axis=1)
        degenerate += int(np.count_nonzero(area <= 1e-15))
    if degenerate == len(faces):
        raise ValueError("All output triangles are degenerate")
    return {"vertices": len(vertices), "triangles": len(faces), "degenerate_triangles": degenerate,
            "bounds": {"min": lo.tolist(), "max": hi.tolist()},
            "rgb_min": colours.min(0).tolist(), "rgb_max": colours.max(0).tolist()}


def write_mesh(path, vertices, faces, colours):
    """Binary format consumed by twin_pipeline: double XYZ, uchar RGB, uint faces."""
    header = ("ply\nformat binary_little_endian 1.0\ncomment NKSR; aligned world metres Z up\n"
              f"element vertex {len(vertices)}\nproperty double x\nproperty double y\nproperty double z\n"
              "property uchar red\nproperty uchar green\nproperty uchar blue\n"
              f"element face {len(faces)}\nproperty list uchar uint vertex_indices\nend_header\n")
    with Path(path).open("xb") as stream:
        stream.write(header.encode("ascii"))
        for start in range(0, len(vertices), BLOCK_POINTS):
            xyz, rgb = vertices[start:start + BLOCK_POINTS], colours[start:start + BLOCK_POINTS]
            block = np.empty(len(xyz), dtype=MESH_DTYPE)
            for i, name in enumerate(("x", "y", "z")):
                block[name] = xyz[:, i]
            for i, name in enumerate(("red", "green", "blue")):
                block[name] = rgb[:, i]
            stream.write(block.tobytes())
        for start in range(0, len(faces), BLOCK_POINTS):
            face = faces[start:start + BLOCK_POINTS]
            block = np.empty(len(face), dtype=FACE_DTYPE)
            block["count"], block["indices"] = 3, face
            stream.write(block.tobytes())
        stream.flush()
        os.fsync(stream.fileno())


def run(args):
    started = time.monotonic()
    output = args.output.resolve()
    report_path = (args.report or output.with_suffix(".nksr.json")).resolve()
    if output == report_path or output == args.input.resolve() or report_path == args.input.resolve():
        raise ValueError("Input, output and report paths must be distinct")
    if output.exists() or report_path.exists():
        raise FileExistsError("Output or report already exists; choose a new output path")
    data = read_cloud(args.input)
    info = {"path": str(args.input.resolve()), "bytes": args.input.stat().st_size,
            "sha256": sha256(args.input), **inspect_cloud(data)}
    preparation = preparation_record(args.provenance, args.input, info)
    xyz, normals, colours, centre, sampling = load_samples(
        data, info, args.max_input_points, args.point_voxel, args.seed)
    del data
    print(f"Validated {info['points']:,} points; retained {len(xyz):,}; bounds {info['bounds']}", flush=True)
    if args.validate_only:
        result = {"schema": "nksr-input-validation/1", "completed": False, "input": info,
                  "preparation": preparation, "sampling": sampling, "centre_world": centre.tolist()}
        print(json.dumps(result, indent=2, allow_nan=False), flush=True)
        return result

    # Heavy imports deliberately occur only after local data/provenance validation.
    import torch
    import nksr
    from nksr.fields.pcnn_field import PCNNField
    from pykdtree.kdtree import KDTree  # Fail early if the official colour dependency is absent.

    if not torch.cuda.is_available():
        raise RuntimeError("NKSR reconstruction requires an available CUDA GPU")
    device = torch.device(args.device)
    if device.type != "cuda":
        raise ValueError("--device must select a CUDA GPU; CPU is used only for fusion")
    torch.manual_seed(args.seed)
    reconstructor = nksr.Reconstructor(device, config="ks")
    base_voxel = float(reconstructor.hparams.voxel_size)
    scale = base_voxel / args.voxel_size
    xyz *= scale
    xyz_tensor, normal_tensor = torch.from_numpy(xyz), torch.from_numpy(normals)
    print(f"Model voxel {base_voxel:g} m; input scale {scale:g}; splitting chunks", flush=True)
    transforms, chunks, features = nksr.split_into_chunks(
        xyz_tensor, chunk_size=args.chunk_size * scale,
        overlap_ratio=args.overlap, normal=normal_tensor)
    if not chunks:
        raise ValueError("No reconstruction chunks; check input spatial extent")
    del normals, normal_tensor
    fields, chunk_stats = [], []
    with torch.no_grad():
        for index in range(len(chunks)):
            points, normal = chunks[index], features["normal"][index]
            count = len(points)
            if count > args.max_chunk_points:
                raise ValueError(f"Chunk {index + 1} has {count:,} points, exceeding --max-chunk-points; "
                                 "decrease --chunk-size or increase --point-voxel")
            chunk_started = time.monotonic()
            print(f"Reconstructing chunk {index + 1}/{len(chunks)} ({count:,} points)", flush=True)
            points_gpu, normals_gpu = points.to(device), normal.to(device)
            field = reconstructor.reconstruct(points_gpu, normal=normals_gpu, detail_level=None)
            if field is None:
                raise RuntimeError(f"NKSR returned an empty field for chunk {index + 1}; no output published")
            field.to_("cpu")
            fields.append(field)
            chunk_stats.append({"index": index, "points": count,
                                "seconds": round(time.monotonic() - chunk_started, 3)})
            # Release completed inputs rather than retaining duplicate overlapping chunks.
            chunks[index], features["normal"][index] = None, None
            del points, normal, points_gpu, normals_gpu, field
            gc.collect()
            torch.cuda.empty_cache()
        del chunks, features
        reconstructor.network.to("cpu")
        torch.cuda.empty_cache()
        print("Fusing completed fields on CPU; extracting coloured mesh", flush=True)
        fused = nksr.FusedField(fields, transforms)
        fused.set_texture_field(PCNNField(xyz_tensor, torch.from_numpy(colours.astype(np.float32) / 255.)))
        mesh = fused.extract_dual_mesh(mise_iter=args.mise_iter, max_points=args.max_eval_points)
        vertices = mesh.v.detach().cpu().numpy().astype(np.float64) / scale + centre
        faces = mesh.f.detach().cpu().numpy()
        if mesh.c is None:
            raise RuntimeError("NKSR did not return vertex colours")
        rgb_float = mesh.c.detach().cpu().numpy()
        if not np.isfinite(rgb_float).all() or rgb_float.min() < -1e-6 or rgb_float.max() > 1.000001:
            raise ValueError("Invalid colour values from nearest-source RGB field")
        rgb = np.rint(np.clip(rgb_float, 0, 1) * 255).astype(np.uint8)
    output_info = mesh_statistics(vertices, faces, rgb)
    report = {"schema": "nksr-reconstruction/1", "method": "NKSR", "completed": True,
              "created_utc": datetime.now(timezone.utc).isoformat(), "coordinate_frame": FRAME,
              "input": info, "preparation": preparation, "sampling": sampling,
              "parameters": {"model": "ks", "voxel_size_metres": args.voxel_size,
                             "model_voxel_size": base_voxel, "input_scale": scale,
                             "centre_world": centre.tolist(), "chunk_size_metres": args.chunk_size,
                             "overlap_ratio": args.overlap, "mise_iter": args.mise_iter,
                             "finest_grid_spacing_metres": args.voxel_size / (2 ** args.mise_iter),
                             "max_eval_points": args.max_eval_points,
                             "max_chunk_points": args.max_chunk_points, "fusion_device": "cpu",
                             "colour_method": "NKSR PCNNField nearest retained measured RGB; no inferred colour",
                             "normal_method": "source oriented normals normalized without reorientation"},
              "software": {"python": sys.version, "numpy": np.__version__, "torch": torch.__version__,
                           "nksr": nksr.__version__, "cuda": torch.version.cuda,
                           "gpu": torch.cuda.get_device_name(device)},
              "chunks": chunk_stats, "script_sha256": sha256(__file__),
              "official_api": "https://github.com/nv-tlabs/NKSR/blob/public/NKSR-USAGE.md"}
    output.parent.mkdir(parents=True, exist_ok=True)
    report_path.parent.mkdir(parents=True, exist_ok=True)
    # Publish the mesh first, and the completion report last. The packager requires both.
    with tempfile.TemporaryDirectory(prefix=".nksr-output-", dir=output.parent) as stage:
        staged_mesh = Path(stage) / "mesh.ply"
        write_mesh(staged_mesh, vertices, faces, rgb)
        report["output"] = {"path": str(output), "bytes": staged_mesh.stat().st_size,
                            "sha256": sha256(staged_mesh), **output_info}
        report["elapsed_seconds"] = round(time.monotonic() - started, 3)
        # Exclusive hard links avoid overwriting even if another process creates the destination.
        os.link(staged_mesh, output)
        with tempfile.NamedTemporaryFile(mode="w", prefix=".nksr-report-", dir=report_path.parent,
                                         delete=False) as stream:
            temp_report = Path(stream.name)
            json.dump(report, stream, indent=2, allow_nan=False)
            stream.write("\n")
            stream.flush()
            os.fsync(stream.fileno())
        try:
            os.link(temp_report, report_path)
        finally:
            temp_report.unlink()
    print(f"Completed {output}: {len(vertices):,} vertices, {len(faces):,} triangles; report {report_path}", flush=True)
    return report


def parser():
    result = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    result.add_argument("--input", type=Path, required=True)
    result.add_argument("--output", type=Path, required=True)
    result.add_argument("--report", type=Path, help="default: output filename with .nksr.json suffix")
    result.add_argument("--provenance", type=Path, help="preparation provenance.json; verified against input hash")
    result.add_argument("--voxel-size", type=float, default=.05, help="NKSR base reconstruction voxel, metres")
    result.add_argument("--chunk-size", type=float, default=6., help="chunk edge length in real metres")
    result.add_argument("--overlap", type=float, default=.10)
    result.add_argument("--point-voxel", type=float, default=.025, help="sampling voxel in metres; 0 disables")
    result.add_argument("--max-input-points", type=int, default=8_000_000, help="seeded stratified input cap; 0 disables")
    result.add_argument("--max-chunk-points", type=int, default=2_000_000, help="fail before allocating an oversized GPU chunk")
    result.add_argument("--mise-iter", type=int, choices=range(4), default=0, help="each step refines extraction grid by 2")
    result.add_argument("--max-eval-points", type=int, default=50_000, help="CPU field evaluation batch limit")
    result.add_argument("--device", default="cuda:0")
    result.add_argument("--seed", type=int, default=0)
    result.add_argument("--validate-only", action="store_true", help="validate inputs and sampling without CUDA or output files")
    return result


def checked_args(argv=None):
    ap = parser()
    args = ap.parse_args(argv)
    for name in ("voxel_size", "chunk_size"):
        if not math.isfinite(getattr(args, name)) or getattr(args, name) <= 0:
            ap.error(f"--{name.replace('_', '-')} must be finite and positive")
    if not math.isfinite(args.point_voxel) or args.point_voxel < 0:
        ap.error("--point-voxel must be finite and nonnegative")
    if not math.isfinite(args.overlap) or not 0 < args.overlap < .5:
        ap.error("--overlap must be greater than 0 and less than 0.5")
    if args.max_input_points < 0 or args.max_chunk_points < 1 or args.max_eval_points < 1 or args.seed < 0:
        ap.error("point limits and seed must be nonnegative; chunk/evaluation limits must be positive")
    return args


if __name__ == "__main__":
    run(checked_args())
